import AppKit
import OSLog

private let pasteLogger = Logger(subsystem: "app.blitztext.mac", category: "Paste")

/// Monotonic seconds, unaffected by changes to the wall clock.
private func uptime() -> TimeInterval {
    ProcessInfo.processInfo.systemUptime
}

/// Pastes text via the clipboard and afterwards restores what the user had copied before.
///
/// Approach: copy every item and type off the clipboard, then put the transcript there as a
/// promise instead of as data. The pasteboard asks Blitztext for the text the moment an app
/// actually reads it, and that request is the signal that the paste landed. The old clipboard
/// goes back once reads have been quiet for a moment, or after a timeout if nothing reads.
/// If anything else writes to the clipboard in the meantime, the newer content stays.
/// `ClipboardRestoreTracker` makes the timing decisions; this class does the AppKit work.
@MainActor
final class ClipboardPasteService {
    static let shared = ClipboardPasteService()

    /// Public markers from nspasteboard.org: clipboard history tools skip items carrying them.
    static let historyMarkers: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private struct PendingPaste {
        let id: Int
        let snapshot: ClipboardSnapshot
        /// Kept alive here because the pasteboard item does not promise to retain it.
        let provider: TranscriptDataProvider?
        var tracker: ClipboardRestoreTracker
    }

    private let pasteboard: NSPasteboard
    private let timings: ClipboardRestoreTimings
    private var pending: PendingPaste?
    private var lastPasteID = 0
    private var checkTask: Task<Void, Never>?

    init(pasteboard: NSPasteboard = .general, timings: ClipboardRestoreTimings = .standard) {
        self.pasteboard = pasteboard
        self.timings = timings
    }

    /// Puts `text` on the clipboard, runs `sendPasteShortcut` and restores the previous
    /// clipboard afterwards.
    func paste(_ text: String, sendPasteShortcut: () -> Void) {
        // The snapshot below must hold the user's content, not an earlier transcript.
        settle(trigger: "new paste")

        guard let snapshot = readableSnapshot() else {
            pasteLogger.notice("Could not read the previous clipboard; the transcript stays on it")
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            sendPasteShortcut()
            return
        }
        lastPasteID += 1
        let id = lastPasteID
        let provider = TranscriptDataProvider(text: text) { [weak self] readAt in
            self?.recordRead(of: id, at: readAt)
        }

        // Current host only: the transcript is meant for this one paste, not for other devices.
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        for marker in Self.historyMarkers {
            item.setData(Data(), forType: marker)
        }
        let promised = item.setDataProvider(provider, forTypes: [.string])
        let lazyWriteWorked = promised && pasteboard.writeObjects([item])
        if !lazyWriteWorked {
            // Without the promise there is no read signal; the no-read timeout restores.
            pasteLogger.error("Could not offer the transcript lazily; pasting plain text")
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
        }

        pending = PendingPaste(
            id: id,
            snapshot: snapshot,
            provider: lazyWriteWorked ? provider : nil,
            tracker: ClipboardRestoreTracker(
                pastedAt: uptime(),
                ownChangeCount: pasteboard.changeCount,
                timings: timings
            )
        )
        pasteLogger.debug("Transcript on the clipboard; saved \(snapshot.items.count) previous items")

        sendPasteShortcut()
        evaluatePending()
    }

    /// Settles a waiting paste right away: restores the previous clipboard if it is still
    /// ours, otherwise leaves the newer content. Called when Blitztext quits.
    func settleNow() {
        settle(trigger: "settled early")
    }

    /// nil when the clipboard lists content that Blitztext may not read (macOS asks the user
    /// before apps read the clipboard on their own). Restoring that empty snapshot would wipe
    /// the transcript as well, so the transcript is better left in place.
    private func readableSnapshot() -> ClipboardSnapshot? {
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            return nil
        }
        let listsContent = !(pasteboard.types ?? []).isEmpty
        let snapshot = ClipboardSnapshot(of: pasteboard)
        if listsContent && snapshot.isEmpty {
            return nil
        }
        return snapshot
    }

    // MARK: - Waiting

    private func recordRead(of id: Int, at readAt: TimeInterval) {
        guard var current = pending, current.id == id else { return }
        current.tracker.recordRead(at: readAt)
        pending = current
        let delay = Int((readAt - current.tracker.pastedAt) * 1000)
        pasteLogger.debug("Transcript read \(delay) ms after the paste shortcut")
        evaluatePending()
    }

    private func evaluatePending() {
        checkTask?.cancel()
        checkTask = nil
        guard let current = pending else { return }

        let decision = current.tracker.decision(at: uptime(), changeCount: pasteboard.changeCount)
        switch decision {
        case .wait(let until):
            let delay = max(0, until - uptime())
            checkTask = Task { [weak self] in
                try? await Task.sleep(for: .seconds(delay))
                guard !Task.isCancelled else { return }
                self?.evaluatePending()
            }
        case .restore, .skip:
            finish(current, decision: decision, trigger: nil)
        }
    }

    private func settle(trigger: String) {
        guard let current = pending else { return }
        checkTask?.cancel()
        checkTask = nil
        let decision = current.tracker.settledDecision(changeCount: pasteboard.changeCount)
        finish(current, decision: decision, trigger: trigger)
    }

    /// `trigger` is nil when the timing rules ended the wait, otherwise why it ended early.
    private func finish(_ paste: PendingPaste, decision: ClipboardRestoreTracker.Decision, trigger: String?) {
        pending = nil
        let tracker = paste.tracker
        let elapsed = Int((uptime() - tracker.pastedAt) * 1000)

        guard decision == .restore else {
            pasteLogger.info("Clipboard changed while waiting; keeping the newer content (\(elapsed) ms)")
            return
        }

        if !paste.snapshot.restore(to: pasteboard) {
            pasteLogger.error("Could not write the previous clipboard back")
            return
        }

        if let firstReadAt = tracker.firstReadAt {
            let firstRead = Int((firstReadAt - tracker.pastedAt) * 1000)
            pasteLogger.info(
                "Restored the previous clipboard after \(elapsed) ms; \(tracker.readCount) reads, first after \(firstRead) ms"
            )
        } else if let trigger {
            pasteLogger.notice(
                "Restored the previous clipboard after \(elapsed) ms before anything read the transcript (\(trigger, privacy: .public))"
            )
        } else {
            pasteLogger.notice(
                "Nothing read the transcript within \(tracker.timings.noReadTimeout, format: .fixed(precision: 1)) s; restored the previous clipboard anyway"
            )
        }
    }
}

// MARK: - Timing decisions

/// How long a paste keeps the transcript on the clipboard.
///
/// Restoring too early makes the target paste the old clipboard, restoring late costs almost
/// nothing (a quick manual Cmd+V would paste the dictation once more). So every value leans
/// towards waiting longer.
struct ClipboardRestoreTimings: Equatable {
    /// Earliest restore after the paste shortcut, even if a read came in at once. The first
    /// read may come from a tool that watches the clipboard instead of from the target, and a
    /// target that reads twice gets the second copy from the pasteboard without asking again,
    /// so Blitztext cannot see it. Nobody reaches for the old clipboard within a second.
    var minimumHold: TimeInterval = 1.0
    /// Quiet time after the last read. Repeated reads of one paste arrive within tens of
    /// milliseconds; half a second leaves an order of magnitude of headroom.
    var quietPeriod: TimeInterval = 0.5
    /// Without any read the paste most likely went nowhere (no text field had focus). Five
    /// seconds also leaves room for a target that is busy for a moment.
    var noReadTimeout: TimeInterval = 5
    /// Hard upper bound, so a reader that never stops cannot hold the clipboard forever.
    var maximumWait: TimeInterval = 15

    static let standard = ClipboardRestoreTimings()
}

/// Pure bookkeeping for one paste: restore now, keep waiting, or leave the clipboard alone.
/// Times are monotonic seconds passed in by the caller, so tests control the clock.
struct ClipboardRestoreTracker {
    enum Decision: Equatable {
        case wait(until: TimeInterval)
        case restore
        /// Someone else wrote to the clipboard; their content wins.
        case skip
    }

    let pastedAt: TimeInterval
    /// Change count right after Blitztext wrote the transcript.
    let ownChangeCount: Int
    let timings: ClipboardRestoreTimings
    private(set) var readCount = 0
    private(set) var firstReadAt: TimeInterval?
    private(set) var lastReadAt: TimeInterval?

    init(pastedAt: TimeInterval, ownChangeCount: Int, timings: ClipboardRestoreTimings = .standard) {
        self.pastedAt = pastedAt
        self.ownChangeCount = ownChangeCount
        self.timings = timings
    }

    mutating func recordRead(at time: TimeInterval) {
        readCount += 1
        firstReadAt = min(firstReadAt ?? time, time)
        lastReadAt = max(lastReadAt ?? time, time)
    }

    /// When the snapshot goes back if nobody else touches the clipboard.
    var restoreAt: TimeInterval {
        let due: TimeInterval
        if let lastReadAt {
            due = max(lastReadAt + timings.quietPeriod, pastedAt + timings.minimumHold)
        } else {
            due = pastedAt + timings.noReadTimeout
        }
        return min(due, pastedAt + timings.maximumWait)
    }

    func decision(at now: TimeInterval, changeCount: Int) -> Decision {
        guard changeCount == ownChangeCount else { return .skip }
        let due = restoreAt
        return now >= due ? .restore : .wait(until: due)
    }

    /// Decision when the wait has to end now (new paste, quit): never `.wait`.
    func settledDecision(changeCount: Int) -> Decision {
        changeCount == ownChangeCount ? .restore : .skip
    }
}

// MARK: - Snapshot

/// Every item and type of a pasteboard, read eagerly so it survives the pasteboard changing.
struct ClipboardSnapshot {
    struct Entry: Equatable {
        let type: NSPasteboard.PasteboardType
        let data: Data
    }

    /// One list per item, types in the original order (readers take the first type they know).
    let items: [[Entry]]

    var isEmpty: Bool {
        items.allSatisfy(\.isEmpty)
    }

    init(of pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { Entry(type: type, data: $0) }
            }
        }
    }

    /// Replaces the pasteboard contents with the snapshot. An empty snapshot leaves it empty.
    @discardableResult
    func restore(to pasteboard: NSPasteboard) -> Bool {
        pasteboard.clearContents()
        let restoredItems = items.compactMap { entries -> NSPasteboardItem? in
            guard !entries.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for entry in entries {
                item.setData(entry.data, forType: entry.type)
            }
            return item
        }
        guard !restoredItems.isEmpty else { return true }
        return pasteboard.writeObjects(restoredItems)
    }
}

// MARK: - Read signal

/// Supplies the transcript when an app reads it and reports each read with its time.
/// AppKit asks once per promised type and serves later reads from its own copy.
private final class TranscriptDataProvider: NSObject, NSPasteboardItemDataProvider {
    private let text: String
    private let onRead: @MainActor @Sendable (TimeInterval) -> Void

    init(text: String, onRead: @escaping @MainActor @Sendable (TimeInterval) -> Void) {
        self.text = text
        self.onRead = onRead
    }

    func pasteboard(
        _ pasteboard: NSPasteboard?,
        item: NSPasteboardItem,
        provideDataForType type: NSPasteboard.PasteboardType
    ) {
        item.setString(text, forType: type)
        let readAt = uptime()
        let onRead = onRead
        // AppKit calls this on the main thread; the hop is only a fallback.
        if Thread.isMainThread {
            MainActor.assumeIsolated { onRead(readAt) }
        } else {
            DispatchQueue.main.async {
                MainActor.assumeIsolated { onRead(readAt) }
            }
        }
    }
}
