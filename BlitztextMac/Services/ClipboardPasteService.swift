import AppKit
import OSLog

private let pasteLogger = Logger(subsystem: "app.blitztext.mac", category: "Paste")

/// Pastes text via the clipboard and afterwards restores what the user had copied before.
///
/// Adapted from MIT-licensed code (see THIRD_PARTY_NOTICES.md): the transcript is
/// published as a *promise* (`declareTypes(_:owner:)`). AppKit calls
/// `pasteboard(_:provideDataForType:)` when an app actually reads it, which is our receipt.
/// The previous clipboard is restored only after that receipt plus a short quiet period,
/// and only if nobody else changed the clipboard in the meantime. The failure mode is
/// "the transcript stays on the clipboard a little longer", never "old content gets pasted".
@MainActor
final class ClipboardPasteService {
    static let shared = ClipboardPasteService()

    /// Wait after the last read before restoring (some apps read twice, e.g. Chromium).
    private static let quietPeriod: TimeInterval = 0.2
    /// Upper bound for how long the transcript occupies the clipboard without any read.
    private static let restoreTimeout: TimeInterval = 8
    private static let pollInterval: TimeInterval = 0.05

    /// Conventions from nspasteboard.org so clipboard managers (Maccy, Paste, Raycast)
    /// skip the transcript. Fewer eager readers means a receipt is more likely the target app.
    private static let concealmentTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private var pending: PendingPaste?

    /// Publishes `text`, runs `sendPasteShortcut` and restores the previous clipboard afterwards.
    func paste(_ text: String, sendPasteShortcut: () -> Void) {
        let pasteboard = NSPasteboard.general
        // A previous paste still holding the clipboard must restore first,
        // otherwise our snapshot would capture the previous transcript.
        settlePending()

        let snapshot = Self.snapshot(of: pasteboard)
        let owner = PromiseOwner(text: text)
        pasteboard.declareTypes([.string] + Self.concealmentTypes, owner: owner)
        let changeCount = pasteboard.changeCount

        sendPasteShortcut()

        let transaction = PendingPaste(
            owner: owner,
            snapshot: snapshot,
            changeCount: changeCount,
            injectedAt: Date()
        )
        pending = transaction
        scheduleEvaluation(for: transaction)
    }

    private func scheduleEvaluation(for transaction: PendingPaste) {
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.pollInterval) { [weak self] in
            guard let self, let pending = self.pending, pending === transaction else { return }
            if self.shouldFinish(pending, now: Date()) {
                self.settlePending()
            } else {
                self.scheduleEvaluation(for: transaction)
            }
        }
    }

    private func shouldFinish(_ transaction: PendingPaste, now: Date) -> Bool {
        if transaction.owner.ownershipLost {
            return true
        }
        if let lastRead = transaction.owner.lastReadAt,
           now.timeIntervalSince(lastRead) >= Self.quietPeriod {
            return true
        }
        return now.timeIntervalSince(transaction.injectedAt) >= Self.restoreTimeout
    }

    private func settlePending() {
        guard let transaction = pending else { return }
        pending = nil

        let pasteboard = NSPasteboard.general
        // Someone copied something else in the meantime: their action wins.
        guard !transaction.owner.ownershipLost,
              pasteboard.changeCount == transaction.changeCount else {
            pasteLogger.info("Clipboard changed during paste, skipping restore")
            return
        }

        if transaction.owner.lastReadAt == nil {
            pasteLogger.info("No app read the transcript before the timeout")
        }

        pasteboard.clearContents()
        if !transaction.snapshot.isEmpty {
            pasteboard.writeObjects(transaction.snapshot)
        }
    }

    private static func snapshot(of pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).compactMap { item in
            let copy = NSPasteboardItem()
            var hasData = false
            for type in item.types {
                if let data = item.data(forType: type) {
                    copy.setData(data, forType: type)
                    hasData = true
                }
            }
            return hasData ? copy : nil
        }
    }
}

private final class PendingPaste {
    let owner: PromiseOwner
    let snapshot: [NSPasteboardItem]
    let changeCount: Int
    let injectedAt: Date

    init(owner: PromiseOwner, snapshot: [NSPasteboardItem], changeCount: Int, injectedAt: Date) {
        self.owner = owner
        self.snapshot = snapshot
        self.changeCount = changeCount
        self.injectedAt = injectedAt
    }
}

/// Supplies the promised transcript when an app reads the clipboard. AppKit calls it on the main thread.
private final class PromiseOwner: NSObject, NSPasteboardTypeOwner {
    let text: String
    private(set) var lastReadAt: Date?
    private(set) var ownershipLost = false

    init(text: String) {
        self.text = text
    }

    func pasteboard(_ sender: NSPasteboard, provideDataForType type: NSPasteboard.PasteboardType) {
        if type == .string {
            sender.setString(text, forType: .string)
            lastReadAt = Date()
        } else {
            sender.setData(Data(), forType: type)
        }
    }

    func pasteboardChangedOwner(_ sender: NSPasteboard) {
        ownershipLost = true
    }
}
